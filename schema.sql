-- Ejecutar este código en Supabase > SQL Editor
-- ==========================================================

create table if not exists public.componentes (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  categoria text not null,
  marca text,
  cantidad integer not null default 0 check (cantidad >= 0),
  estado text not null,
  descripcion text,
  fecha_registro date not null default current_date
);

-- Activar RLS
alter table public.componentes enable row level security;

-- Para una demostración escolar SIN login:
-- permite lectura, inserción, modificación y eliminación
-- usando la clave pública anon.
-- Si después agregás Authentication, estas reglas deben hacerse
-- más restrictivas.

drop policy if exists "lectura_componentes" on public.componentes;
create policy "lectura_componentes"
on public.componentes
for select
to anon
using (true);

drop policy if exists "insertar_componentes" on public.componentes;
create policy "insertar_componentes"
on public.componentes
for insert
to anon
with check (true);

drop policy if exists "modificar_componentes" on public.componentes;
create policy "modificar_componentes"
on public.componentes
for update
to anon
using (true)
with check (true);

drop policy if exists "eliminar_componentes" on public.componentes;
create policy "eliminar_componentes"
on public.componentes
for delete
to anon
using (true);

